#!/usr/bin/env bash
# run.sh —— 一键启动脚本：编译并对比基线与实验组
#
# 用法：
#   ./run.sh                # 跑基线 + 实验组默认 8 线程
#   ./run.sh 24             # 跑基线 + 实验组 24 线程
#   ./run.sh sweep          # 跑基线 + 实验组多线程数扫描（4/8/16/24/32/64）

set -e

cd "$(dirname "$0")"

# ---------- 编译 ----------
if [ ! -x ./SearchRandom ] || [ ! -x ./Thread ]; then
    echo "==> 编译中..."
    make clean >/dev/null
    make >/dev/null
    echo "==> 编译完成"
fi
echo

# ---------- 基线：单线程原版 ----------
echo "================================================================"
echo "  [基线] SearchRandom  （单线程，拼主频）"
echo "================================================================"
time ./SearchRandom
echo

# ---------- 实验组：多线程 + AVX2 + 内嵌汇编 ----------
if [ "$1" = "sweep" ]; then
    echo "================================================================"
    echo "  [实验组] Thread  多线程数扫描"
    echo "================================================================"
    for n in 4 8 16 24 32 64; do
        echo "---- 线程数 = $n ----"
        time ./Thread "$n"
        echo
    done
else
    N="${1:-8}"
    echo "================================================================"
    echo "  [实验组] Thread  线程数 = $N"
    echo "================================================================"
    time ./Thread "$N"
fi
